import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const DOCS_DIR = path.join(ROOT, 'docs');

export async function loadSources() {
  const raw = await fs.readFile(path.join(ROOT, 'docs-sources.json'), 'utf8');
  return JSON.parse(raw);
}

export function enabled(list = []) {
  return list.filter((entry) => entry.enabled !== false);
}

// Remove everything in a generated folder so deleted sources disappear from the site.
export async function resetDir(dir, category) {
  await fs.rm(dir, {recursive: true, force: true});
  await fs.mkdir(dir, {recursive: true});
  if (category) {
    await fs.writeFile(path.join(dir, '_category_.json'), JSON.stringify(category, null, 2) + '\n');
  }
}

// If the document starts with an H1, use it as the title and drop it (Docusaurus renders the title itself).
export function extractTitle(markdown, fallback) {
  const match = markdown.match(/^\s*#\s+(.+?)\s*#*\s*$/m);
  if (match && markdown.trimStart().startsWith('#') && !markdown.trimStart().startsWith('##')) {
    return {title: match[1].replace(/[*_`]/g, '').trim(), body: markdown.replace(match[0], '').trimStart()};
  }
  return {title: fallback, body: markdown};
}

// lastUpdate: {date, author?} — when the source last changed. Docusaurus shows it at the bottom of
// the page ("Last updated on … by …"), and the MCP server includes it in search results.
export async function writeDoc(dir, {slug, title, description, position, lastUpdate, source, origin, body}) {
  const frontMatter = [
    '---',
    `title: ${JSON.stringify(title)}`,
    ...(description ? [`description: ${JSON.stringify(description)}`] : []),
    ...(position !== undefined ? [`sidebar_position: ${position}`] : []),
    ...(lastUpdate?.date
      ? [
          'last_update:',
          `  date: ${new Date(lastUpdate.date).toISOString().slice(0, 10)}`,
          ...(lastUpdate.author ? [`  author: ${JSON.stringify(lastUpdate.author)}`] : []),
        ]
      : []),
    `custom_edit_url: ${source ? JSON.stringify(source) : 'null'}`,
    '---',
    '',
    `<!-- GENERATED by scripts/sync — do not edit here. Edit the source: ${source ?? origin ?? 'n/a'} -->`,
    '',
  ].join('\n');
  // Always .md (CommonMark), so stray `<` / `{` in imported content can't break the MDX parser.
  const file = path.join(dir, `${slug}.md`);
  await fs.writeFile(file, frontMatter + body.trimEnd() + '\n');
  return path.relative(ROOT, file);
}

// First real paragraph of a page as plain text (skips badges, images, headings and HTML),
// for the card text on overview pages.
export function summarize(markdown, max = 160) {
  const paragraph = markdown
    .replace(/^<!--[\s\S]*?-->/gm, '')
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .find((p) => p && !/^(#|<|!\[|\[!\[|```|\||:::|>)/.test(p));
  if (!paragraph) return undefined;
  const text = paragraph
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\](\[[^\]]*\])?/g, '$1') // reference links: [text][ref], [text]
    .replace(/<(https?:[^>]+)>/g, '$1')
    .replace(/[*_`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return text.length > max ? `${text.slice(0, max - 1).replace(/\s+\S*$/, '')}…` : text;
}

export function log(step, message) {
  console.log(`[${step}] ${message}`);
}

// Local-only sources (Drive downloads, Box) leave no trace when their files aren't on this
// machine: remove a section folder once none of its entries produced pages.
export async function dropEmptySection(dir) {
  const entries = await fs.readdir(dir, {withFileTypes: true}).catch(() => null);
  if (entries && !entries.some((e) => e.isDirectory())) await fs.rm(dir, {recursive: true, force: true});
}

// Fingerprint of a set of source files (path, size, modified time), saved next to the generated
// pages so unchanged sources aren't converted again on every `make up`. SYNC_FORCE=1 converts anyway.
const STAMP_FILE = '.source-stamp';

export async function fingerprint(files) {
  const hash = crypto.createHash('sha1');
  for (const file of files) {
    const {size, mtimeMs} = await fs.stat(file);
    hash.update(`${file}\0${size}\0${mtimeMs}\n`);
  }
  return hash.digest('hex');
}

export async function isUpToDate(outDir, stamp) {
  if (process.env.SYNC_FORCE) return false;
  return (await fs.readFile(path.join(outDir, STAMP_FILE), 'utf8').catch(() => null)) === stamp;
}

export async function writeStamp(outDir, stamp) {
  await fs.writeFile(path.join(outDir, STAMP_FILE), stamp);
}

// GitHub alert blockquotes (> [!NOTE] ...) → Docusaurus admonitions (:::note ... :::).
const ALERT_TYPES = {note: 'note', tip: 'tip', important: 'info', warning: 'warning', caution: 'danger'};
export function convertGithubAlerts(markdown) {
  return markdown.replace(
    /^> *\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\][^\n]*\n((?:>.*(?:\n|$))*)/gim,
    (match, type, body) => `:::${ALERT_TYPES[type.toLowerCase()]}\n\n${body.replace(/^> ?/gm, '').trim()}\n\n:::\n`,
  );
}
