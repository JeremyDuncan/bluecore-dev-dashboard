// Builds the "Project Status" section: GitHub project boards, open repo issues and release notes.
//
// Writes docs/<dir>/ (git-ignored: boards are often private):
//   <board slug>.mdx  live board component + a text version (for search and the MCP server)
//   issues.mdx        open issues per repo, same idea
//   whats-new.mdx     latest release of each repo ("Updates") and a release timeline
//   tests.mdx         every test suite at a glance: the integration suite and each repo's own tests
//   integration-tests.mdx, tests-<repo>.mdx  one suite: pass rate, durations, failing tests, recent runs
//   index.mdx         overview cards linking to every page
//   _data/*.json      the snapshot the pages show until (or unless) live data loads
//   _data/nav.json    the pages of this build, for the icon navigation (StatusNav) on every page
//
// The sidebar shows the section as one link (customProps.hideItems in _category_.json, see
// sidebarItemsGenerator in docusaurus.config.js); the pages link to each other with icons instead.
//
// PUBLIC_BUILD=1 (the GitHub Pages deploy) leaves out project boards, which are private, unless
// their entry in docs-sources.json says "public": true.
//
// The pages refresh themselves from the MCP container's /api/github endpoints (see mcp/server.mjs).
// Needs GITHUB_TOKEN with the read:project scope.
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {ciMetrics, failureStage, formatDuration, triggerName} from '../../mcp/ci-metrics.mjs';
import {fetchIssues, fetchProject, fetchReleases, fetchWorkflowRuns, logCacheFromSnapshot, testSuites} from '../../mcp/github.mjs';
import {DOCS_DIR, loadSources, log} from './lib.mjs';

// Escape Markdown/MDX syntax in text that comes from GitHub (issue titles, labels, …)
const esc = (s) => String(s ?? '').replace(/[\\`*_{}[\]<>#|!]/g, '\\$&');
const day = (iso) => (iso ? iso.slice(0, 10) : '');
const stamp = (iso) => `${iso.slice(0, 16).replace('T', ' ')} UTC`;

function itemLine(i) {
  const ref = i.repo && i.number ? `${i.repo}#${i.number}` : i.kind === 'draft' ? 'draft' : '';
  const title = i.url ? `[${esc(i.title)}](${i.url})` : esc(i.title);
  const meta = [
    ref && `\`${ref}\``,
    i.kind === 'pr' && 'pull request',
    i.assignees.length && i.assignees.map((a) => `@${esc(a)}`).join(', '),
    i.labels.length && i.labels.map((l) => esc(l.name)).join(', '),
    i.milestone && `milestone: ${esc(i.milestone)}`,
    i.subIssues && `${i.subIssues.completed}/${i.subIssues.total} sub-issues done`,
  ].filter(Boolean);
  return `- ${title}${meta.length ? ` — ${meta.join(' · ')}` : ''}`;
}

// Front matter and imports every page shares: the sidebar stays visible although the pages aren't
// listed in it, and the icon navigation sits at the top.
// last_update is the sync date: the data is as fresh as the last sync (or live), never stale.
const pageMeta = `hide_table_of_contents: true\ndisplayed_sidebar: docs\ncustom_edit_url: null\nlast_update:\n  date: ${new Date().toISOString().slice(0, 10)}`;
const navBlock = (id) =>
  `import StatusNav from '@site/src/components/ProjectStatus/StatusNav';\nimport nav from './_data/nav.json';\n\n<StatusNav pages={nav} current="${id}" />`;

function boardPage(board, {slug, dataFile, position}) {
  const statuses = [...board.statuses.map((s) => s.name), null];
  const sections = statuses.map((status) => {
    let items = board.items.filter((i) => i.status === status);
    if (items.length === 0) return '';
    let note = '';
    if (status === 'Done') {
      items = [...items].sort((a, b) => (b.closedAt ?? b.updatedAt ?? '').localeCompare(a.closedAt ?? a.updatedAt ?? ''));
      if (items.length > 50) note = `\n\n*${items.length - 50} older items not listed.*`;
      items = items.slice(0, 50);
    }
    const count = board.items.filter((i) => i.status === status).length;
    return `### ${esc(status ?? 'No status')} (${count})\n\n${items.map(itemLine).join('\n')}${note}`;
  });
  return `---
title: ${JSON.stringify(board.title)}
description: ${JSON.stringify(`Status of the ${board.title} GitHub project board`)}
sidebar_position: ${position}
${pageMeta}
---

{/* GENERATED by scripts/sync/project-status.mjs — do not edit. Source: ${board.url} */}

import ProjectBoard from '@site/src/components/ProjectStatus/ProjectBoard';
import snapshot from './_data/${dataFile}';
${navBlock(slug)}

<ProjectBoard snapshot={snapshot} apiPath="/github/project/${board.org}/${board.number}" />

<details>
<summary>Text version (as of the last sync, ${stamp(board.fetchedAt)})</summary>

${sections.filter(Boolean).join('\n\n')}

</details>
`;
}

function issuesPage(data, {dataFile, position}) {
  const total = data.repos.reduce((n, r) => n + r.issues.length, 0);
  const sections = data.repos
    .filter((r) => r.issues.length)
    .map((r) => {
      const lines = r.issues.map(
        (i) =>
          `- [${esc(i.title)}](${i.url}) — \`#${i.number}\`` +
          (i.labels.length ? ` · ${i.labels.map((l) => esc(l.name)).join(', ')}` : '') +
          (i.assignees.length ? ` · ${i.assignees.map((a) => `@${esc(a)}`).join(', ')}` : '') +
          ` · updated ${day(i.updatedAt)}`,
      );
      return `### ${esc(r.name)} (${r.issues.length})\n\n${lines.join('\n')}`;
    });
  return `---
title: "Repo Issues"
description: ${JSON.stringify(`Open issues across the ${data.org} repositories`)}
sidebar_position: ${position}
${pageMeta}
---

{/* GENERATED by scripts/sync/project-status.mjs — do not edit. Source: https://github.com/${data.org} */}

import RepoIssues from '@site/src/components/ProjectStatus/RepoIssues';
import snapshot from './_data/${dataFile}';
${navBlock('issues')}

<RepoIssues snapshot={snapshot} apiPath="/github/issues/${data.org}" />

<details>
<summary>Text version: ${total} open issues (as of the last sync, ${stamp(data.fetchedAt)})</summary>

${sections.join('\n\n')}

</details>
`;
}

function whatsNewPage(data, {dataFile, position}) {
  // Text version: the latest 40 releases with their highlights
  const lines = data.releases.slice(0, 40).map(
    (r) =>
      `- **${esc(r.repo)} [${esc(r.name)}](${r.url})** — ${day(r.publishedAt)}` +
      (r.highlights.length ? `: ${r.highlights.map((h) => esc(h.replace(/https?:\/\/\S+/g, '').replace(/\s+by @\S+\s*(in)?\s*$/, '').trim())).join('; ')}` : ''),
  );
  return `---
title: "What's New"
description: ${JSON.stringify(`Latest releases of the ${data.org} repositories`)}
sidebar_position: ${position}
${pageMeta}
---

{/* GENERATED by scripts/sync/project-status.mjs — do not edit. Source: GitHub releases of ${data.org} */}

import WhatsNew from '@site/src/components/ProjectStatus/WhatsNew';
import snapshot from './_data/${dataFile}';
${navBlock('whats-new')}

<WhatsNew snapshot={snapshot} apiPath="/github/releases/${data.org}" />

<details>
<summary>Text version: latest releases (as of the last sync, ${stamp(data.fetchedAt)})</summary>

${lines.join('\n')}

</details>
`;
}

const suiteTitle = (suite) => suite.pageTitle ?? (suite.kind === 'integration' ? 'Integration Tests' : `${suite.title ?? suite.repo} tests`);

// One row per suite for the Tests overview page (TestsOverview reads _data/tests.json)
function suiteSummary(data, suite, href) {
  const m = ciMetrics(data);
  const latest = data.runs.find((r) => r.conclusion === 'success' || r.conclusion === 'failure') ?? null;
  return {
    id: suite.slug,
    href,
    kind: suite.kind,
    title: suite.kind === 'integration' ? suiteTitle(suite) : (suite.title ?? suite.repo),
    repo: suite.repo,
    workflow: data.name,
    url: data.url,
    latest: latest && {conclusion: latest.conclusion, number: latest.number, url: latest.url, createdAt: latest.createdAt},
    passRate: m.passRate.window,
    last7Days: m.passRate.last7Days,
    runs: m.window.runs,
    streak: m.streak,
    medianSec: m.duration.medianSec,
    tests: m.latestTests && {passed: m.latestTests.passed, failed: m.latestTests.failed + m.latestTests.errors, skipped: m.latestTests.skipped},
    failingNow: m.failingNow,
    runsPerDay: m.runsPerDay,
    fetchedAt: data.fetchedAt,
  };
}

function testsOverviewPage({position}) {
  return `---
title: "Tests"
description: "Test health of the integration suite and of each Blue Core repository."
sidebar_position: ${position}
${pageMeta}
---

{/* GENERATED by scripts/sync/project-status.mjs — do not edit. */}

import TestsOverview from '@site/src/components/ProjectStatus/TestsOverview';
import suites from './_data/tests.json';
${navBlock('tests')}

<TestsOverview suites={suites} />
`;
}

function integrationTestsPage(data, suite, {dataFile, position, slug}) {
  const m = ciMetrics(data);
  const pct = (v) => (v === null ? '–' : `${v}%`);
  const runs = data.runs.slice(0, 20).map(
    (r) =>
      `- [#${r.number}](${r.url}) ${r.status === 'completed' ? r.conclusion : r.status} — ${day(r.createdAt)} · ${formatDuration(r.durationSec)} · ${esc(triggerName(r))}` +
      (r.tests ? ` · tests ${r.tests.passed} passed, ${r.tests.failed} failed` : '') +
      (r.conclusion === 'failure' ? ` · failed in ${failureStage(r)}` : ''),
  );
  const tests = m.topFailingTests.slice(0, 10).map(
    (t) => `- \`${esc(t.test)}\` — failed ${t.failures} times, ${t.failingNow ? 'still failing' : `passing since ${day(t.passedSince)}`}${t.lastMessage ? `: ${esc(t.lastMessage.slice(0, 160))}` : ''}`,
  );
  return `---
title: ${JSON.stringify(suiteTitle(suite))}
description: ${JSON.stringify(`Health of the ${data.name} workflow in ${suite.repo}`)}
sidebar_position: ${position}
${pageMeta}
---

{/* GENERATED by scripts/sync/project-status.mjs — do not edit. Source: ${data.url} */}

import IntegrationTests from '@site/src/components/ProjectStatus/IntegrationTests';
import snapshot from './_data/${dataFile}';
${navBlock(slug)}

<IntegrationTests snapshot={snapshot} apiPath="/github/ci/${data.org}/${data.repo}/${data.workflow}" kind="${suite.kind}" />

<details>
<summary>Text version (as of the last sync, ${stamp(data.fetchedAt)})</summary>

**${esc(data.name)}** in ${esc(suite.repo)}: last ${m.window.runs} runs since ${day(m.window.since)}. Pass rate ${pct(m.passRate.window)} (${m.counts.success} passed, ${m.counts.failure} failed, ${m.counts.cancelled} cancelled); last 7 days ${pct(m.passRate.last7Days)}. Median duration ${formatDuration(m.duration.medianSec)}, p90 ${formatDuration(m.duration.p90Sec)}. Current streak: ${m.streak.runs} ${m.streak.kind === 'success' ? 'passing' : 'failing'} runs. Failures by stage: ${Object.entries(m.failureStages).map(([k, v]) => `${k} ${v}`).join(', ') || 'none'}.${m.latestTests ? ` Latest test results: ${m.latestTests.passed} passed, ${m.latestTests.failed} failed, ${m.latestTests.skipped} skipped.` : ''}

### Most-failing tests

${tests.join('\n') || 'None in the runs read.'}

### Recent runs

${runs.join('\n')}

</details>
`;
}

