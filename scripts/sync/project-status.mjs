export async function syncProjectStatus() {
  const config = (await loadSources()).projectStatus;
  if (!config || config.enabled === false) return;
  const token = process.env.GITHUB_TOKEN;
  const dirName = config.dir ?? 'project-status';
  const target = path.join(DOCS_DIR, dirName);
  if (!token) {
    log('project-status', '- GITHUB_TOKEN not set, leaving existing pages as they are');
    return;
  }

  // Build in a staging folder and swap it in only if everything was fetched
  const staging = await fs.mkdtemp(path.join(os.tmpdir(), 'status-'));
  await fs.chmod(staging, 0o755);
  try {
    await fs.mkdir(path.join(staging, '_data'));
    await fs.writeFile(
      path.join(staging, '_category_.json'),
      JSON.stringify(
        {
          label: config.title ?? 'Project Status',
          ...(config.position !== undefined && {position: config.position}),
          link: {type: 'doc', id: `${dirName}/index`},
          customProps: {hideItems: true},
        },
        null,
        2,
      ) + '\n',
    );

    const title = config.title ?? 'Project Status';
    const nav = [{id: 'overview', icon: 'overview', label: 'Overview', title, href: `/${dirName}`, description: 'All Project Status pages in one place.'}];
    const add = (id, icon, label, pageTitle, description) => nav.push({id, icon, label, title: pageTitle, href: `/${dirName}/${id}`, description});
    const pct = (v) => (v === null ? 'no' : `${v}%`);

    let position = 1;
    for (const p of config.projects ?? []) {
      if (process.env.PUBLIC_BUILD && !p.public) {
        log('project-status', `- ${p.org}/projects/${p.number}: left out of the public build (private board)`);
        continue;
      }
      const board = await fetchProject(p, token);
      const slug = p.slug ?? `${p.org}-${p.number}`;
      const dataFile = `project-${p.org}-${p.number}.json`;
      await fs.writeFile(path.join(staging, '_data', dataFile), JSON.stringify(board));
      await fs.writeFile(path.join(staging, `${slug}.mdx`), boardPage(board, {slug, dataFile, position: position++}));
      const open = board.items.filter((i) => i.status !== 'Done').length;
      add(slug, 'board', 'Board', board.title, `${open} open items across ${board.statuses.length} status columns${board.public ? '' : ' (private board)'}. Filter by repo, assignee or label.`);
      log('project-status', `✓ ${dirName}/${slug} (${board.title}: ${board.items.length} items${board.public ? '' : ', private board'})`);
    }

    if (config.issues) {
      const data = await fetchIssues(config.issues, token);
      const dataFile = `issues-${data.org}.json`;
      await fs.writeFile(path.join(staging, '_data', dataFile), JSON.stringify(data));
      await fs.writeFile(path.join(staging, 'issues.mdx'), issuesPage(data, {dataFile, position: position++}));
      const total = data.repos.reduce((n, r) => n + r.issues.length, 0);
      const withIssues = data.repos.filter((r) => r.issues.length).length;
      add('issues', 'issues', 'Issues', 'Repo Issues', `${total} open issues across ${withIssues} ${data.org} repositories, grouped by repo. Filter by repo, label or assignee.`);
      log('project-status', `✓ ${dirName}/issues (${total} open issues in ${data.repos.length} repos)`);
    }

    // Tests: an overview page, then one page per suite (integration and each repo's own tests). In the
    // icon navigation the suite pages form a second row under "Tests" (group: 'tests').
    const suites = testSuites(config);
    if (suites.length) {
      const summaries = [];
      const testsPosition = position++;
      add('tests', 'tests', 'Tests', 'Tests', '');
      const testsNav = nav[nav.length - 1];
      for (const suite of suites) {
        // Logs read by the last sync (or restored by CI's cache) don't need downloading again
        const previous = await fs.readFile(path.join(target, '_data', suite.dataFile), 'utf8').then(JSON.parse).catch(() => null);
        const data = await fetchWorkflowRuns(suite, token, logCacheFromSnapshot(previous));
        const slug = suite.slug;
        await fs.writeFile(path.join(staging, '_data', suite.dataFile), JSON.stringify(data));
        await fs.writeFile(path.join(staging, `${slug}.mdx`), integrationTestsPage(data, suite, {dataFile: suite.dataFile, slug, position: position++}));
        const summary = suiteSummary(data, suite, `/${dirName}/${slug}`);
        summaries.push(summary);
        const tests = summary.tests ? ` Latest results: ${summary.tests.passed} passed, ${summary.tests.failed} failed.` : '';
        nav.push({
          id: slug,
          group: 'tests',
          icon: 'tests',
          label: suite.kind === 'integration' ? 'Integration' : (suite.title ?? suite.repo),
          title: suiteTitle(suite),
          href: summary.href,
          status: summary.latest?.conclusion ?? null,
          description: `${data.name} in ${suite.repo}: ${pct(summary.passRate)} pass rate over the last ${summary.runs} runs.${tests}`,
        });
        log('project-status', `✓ ${dirName}/${slug} (${data.name}: ${data.runs.length} runs, test results read from ${data.runs.filter((r) => r.tests).length})`);
      }
      const failing = summaries.filter((x) => x.latest?.conclusion === 'failure').length;
      testsNav.description = `${summaries.length} test suites: the integration suite and each repo's own tests. ${failing ? `${failing} failing on their latest run.` : 'All passing on their latest run.'}`;
      await fs.writeFile(path.join(staging, '_data', 'tests.json'), JSON.stringify(summaries, null, 2));
      await fs.writeFile(path.join(staging, 'tests.mdx'), testsOverviewPage({position: testsPosition}));
    }

    if (config.releases) {
      const data = await fetchReleases(config.releases, token);
      const dataFile = `releases-${data.org}.json`;
      await fs.writeFile(path.join(staging, '_data', dataFile), JSON.stringify(data));
      await fs.writeFile(path.join(staging, 'whats-new.mdx'), whatsNewPage(data, {dataFile, position: position++}));
      const withReleases = new Set(data.releases.map((r) => r.repo)).size;
      add('whats-new', 'releases', "What's New", "What's New", `The latest release of ${withReleases} repositories, then a timeline of ${data.releases.length} releases with their notes.`);
      log('project-status', `✓ ${dirName}/whats-new (${data.releases.length} releases from ${withReleases} repos)`);
    }

    await fs.writeFile(path.join(staging, '_data', 'nav.json'), JSON.stringify(nav, null, 2));
    await fs.writeFile(path.join(staging, 'index.mdx'), overviewPage(title));

    await fs.rm(target, {recursive: true, force: true});
    await fs.cp(staging, target, {recursive: true});
  } catch (err) {
    log('project-status', `✗ ${err.message} (kept existing pages)`);
    process.exitCode = 1;
  } finally {
    await fs.rm(staging, {recursive: true, force: true});
  }
}

if (import.meta.url === `file://${process.argv[1]}`) await syncProjectStatus();
