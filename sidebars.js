// @ts-check
import fs from 'node:fs';

// Two sidebars, generated from the docs/ folder structure (see sidebarItemsGenerator in
// docusaurus.config.js):
// - docs: the documentation. Control order/labels with `sidebar_position` front matter or
//   `_category_.json` files.
// - guides: how this site works (hand-written guides), reached from the "?" in the navbar.
// - status: the Project Status dashboard (live GitHub data), kept apart from the docs. Its pages set
//   `displayed_sidebar: status`; its items come from the sync's _data/nav.json.

const has = (dir) => fs.existsSync(new URL(`./docs/${dir}`, import.meta.url));

/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */
const sidebars = {
  docs: [{type: 'autogenerated', dirName: '.'}],
  ...(has('guides') && {guides: [{type: 'autogenerated', dirName: 'guides'}]}),
  ...(has('project-status') && {status: [{type: 'autogenerated', dirName: 'project-status'}]}),
};

export default sidebars;
